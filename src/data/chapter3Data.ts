export function CH3_ZONE_NAMES(x: number, floor: number, room: Ch3RoomId): string {
  if (room === 'protagonist_house') return 'ภายในบ้านของภีม (ห้องนอน & ห้องรับแขก)';
  if (room === 'classroom_2b') return 'ภายในห้องเรียน ม.5/2 (ตึกเรียนชั้น 2)';
  if (room === 'teacher_office') return 'ภายในห้องพักครูหมวดศิลปะ (ชั้น 1)';
  if (room === 'library_room') return 'ภายในหอสมุด & หอจดหมายเหตุ (ชั้น 1)';
  if (room === 'music_room') return 'ห้องดนตรีไทย & นาฏศิลป์ต้องคำสาป (ชั้น 3)';

  if (floor === 1) return 'ระเบียงชั้น 1 อาคารเรียน — ห้องสมุด / ห้องพักครู / ล็อกเกอร์';
  if (floor === 2) return 'ระเบียงชั้น 2 อาคารเรียน — ห้อง ม.5/2 / ห้องน้ำ / ตู้ล็อกเกอร์';
  if (floor === 3) return 'ระเบียงชั้น 3 เขตหวงห้าม — ห้องดนตรีไทย & นาฏศิลป์';

  if (x < -94) return 'หน้าบ้านพักของภีม & ซอยบ้านสวน';
  if (x < -56) return 'ถนนหน้าโรงเรียน — ป้ายรถเมล์ & ร้านค้า';
  if (x < -14) return 'ซุ้มประตูโรงเรียนมัธยมจันทรารัตน์ & ลานเสาธง';
  if (x < 64) return 'ลานหน้าตึกเรียนใหญ่ 3 ชั้น (บันไดขึ้นชั้น 1–3 อยู่ฝั่งขวา)';
  if (x < 98) return 'โรงอาหารกลาง & สหกรณ์โรงเรียน / สนามบาส';
  return 'สวนหย่อมหลังโรงเรียน & ศาลตายายใต้ต้นโพธิ์';
}
